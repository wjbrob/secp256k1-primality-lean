#!/usr/bin/env python3
"""Generate `Secp256k1Primality/Order/Cert.lean`: the secp256k1 generator-order certificate.

The certificate is an addition chain for (n - 1)·G, built by double-and-add over the bits of
n - 1. Every step records the resulting affine point and the line slope `l`, so that Lean can
check it *without any field inversion* via `add_step` / `dbl_step` (see `Order/Curve.lean`); a
final `neg_step` shows (n - 1)·G + G = 0, i.e. n·G = 0.

Before anything is emitted, every point of the chain is cross-checked against an independent
scalar multiplication (a constant-pattern Montgomery ladder in projective coordinates, which
shares no code path with the affine chain). Output is deterministic, so

    python3 scripts/gen_order_cert.py --check

verifies that the committed Cert.lean is exactly what this script produces.

Usage:
    python3 scripts/gen_order_cert.py [--out PATH] [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# secp256k1 domain parameters (SEC 2, v2.0, section 2.4.1).
P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "Secp256k1Primality/Order/Cert.lean"

HEADER = """\
/-
  Secp256k1Primality.Order.Cert -- GENERATED by `scripts/gen_order_cert.py`;
  do not edit by hand.

  An addition chain for (n - 1)·G on secp256k1: {steps} steps ({dbl} doublings, {add} additions),
  each checked inverse-free by `dbl_step` / `add_step`, then `neg_step` for (n - 1)·G + G = 0.
  Every point is cross-checked against an independent scalar multiplication before emission.
  The step facts are private; the public result is `cert_nsmul_eq_zero`.
-/
import Secp256k1Primality.Order.Curve

namespace Secp256k1Primality.Order

open WeierstrassCurve.Affine

/-- The generator, with coordinates as natural-number casts, is on the curve. -/
theorem G_nonsingular_nat : W.Nonsingular (({gx} : ℕ) : ZMod P) (({gy} : ℕ) : ZMod P) :=
  ns (by decide)

private theorem t0 : Point.some G_nonsingular_nat = (1 : ℕ) • Point.some G_nonsingular_nat :=
  (one_nsmul _).symm
"""


def _inv(a: int) -> int:
    return pow(a % P, -1, P)


def chain() -> list[dict]:
    """The certificate steps: op, scalar k, resulting affine point, slope l."""
    steps: list[dict] = []
    x, y, k = GX, GY, 1
    for bit in bin(N - 1)[3:]:
        lam = 3 * x * x * _inv(2 * y) % P
        x3 = (lam * lam - 2 * x) % P
        y3 = (lam * (x - x3) - y) % P
        k *= 2
        steps.append({"op": "dbl", "k": k, "x": x3, "y": y3, "l": lam})
        x, y = x3, y3
        if bit == "1":
            lam = (y - GY) * _inv(x - GX) % P
            x3 = (lam * lam - x - GX) % P
            y3 = (lam * (x - x3) - y) % P
            k += 1
            steps.append({"op": "add", "k": k, "x": x3, "y": y3, "l": lam})
            x, y = x3, y3
    return steps


# --- independent scalar multiplication: projective Montgomery-style ladder ---------------
# Deliberately a different algorithm and coordinate system from chain() above, so that an
# arithmetic slip in one is not mirrored by the other.


def _proj_double(pt: tuple[int, int, int]) -> tuple[int, int, int]:
    x, y, z = pt
    if y % P == 0 or z % P == 0:
        return (0, 1, 0)
    w = 3 * x * x % P
    s = y * z % P
    b = x * y * s % P
    h = (w * w - 8 * b) % P
    return (2 * h * s % P, (w * (4 * b - h) - 8 * y * y * s * s) % P, 8 * s * s * s % P)


def _proj_add(a: tuple[int, int, int], b: tuple[int, int, int]) -> tuple[int, int, int]:
    x1, y1, z1 = a
    x2, y2, z2 = b
    if z1 % P == 0:
        return b
    if z2 % P == 0:
        return a
    u1, u2 = y2 * z1 % P, y1 * z2 % P
    v1, v2 = x2 * z1 % P, x1 * z2 % P
    if v1 == v2:
        return _proj_double(a) if u1 == u2 else (0, 1, 0)
    u, v = (u1 - u2) % P, (v1 - v2) % P
    w = z1 * z2 % P
    v2_ = v * v % P
    v3 = v2_ * v % P
    r = v2_ * v2 % P
    aa = (u * u * w - v3 - 2 * r) % P
    return (v * aa % P, (u * (r - aa) - v3 * u2) % P, v3 * w % P)


def ladder_mul(k: int) -> tuple[int, int]:
    """k·G as an affine pair, by a ladder over projective coordinates."""
    r0: tuple[int, int, int] = (0, 1, 0)
    r1: tuple[int, int, int] = (GX, GY, 1)
    for bit in bin(k)[2:]:
        if bit == "0":
            r1 = _proj_add(r0, r1)
            r0 = _proj_double(r0)
        else:
            r0 = _proj_add(r0, r1)
            r1 = _proj_double(r1)
    x, y, z = r0
    if z % P == 0:
        raise AssertionError("ladder reached the point at infinity")
    zi = _inv(z)
    return (x * zi % P, y * zi % P)


def cross_check(steps: list[dict]) -> None:
    """Every chain point must equal ladder_mul(k); the chain must end at -G = (n-1)·G."""
    for s in steps:
        if not (s["y"] * s["y"] - s["x"] ** 3 - 7) % P == 0:
            raise AssertionError(f"chain point for k={s['k']:#x} is not on the curve")
        if ladder_mul(s["k"]) != (s["x"], s["y"]):
            raise AssertionError(f"chain point for k={s['k']:#x} disagrees with the ladder")
    last = steps[-1]
    if last["k"] != N - 1 or last["x"] != GX or (last["y"] + GY) % P != 0:
        raise AssertionError("chain does not end at (n-1)G = -G")


def generate() -> str:
    steps = chain()
    cross_check(steps)
    n_dbl = sum(s["op"] == "dbl" for s in steps)
    out = [HEADER.format(steps=len(steps), dbl=n_dbl, add=len(steps) - n_dbl, gx=GX, gy=GY)]
    for i, s in enumerate(steps, start=1):
        prev = f"t{i - 1}"
        out.append(
            f"private theorem ns{i} : W.Nonsingular (({s['x']} : ℕ) : ZMod P) "
            f"(({s['y']} : ℕ) : ZMod P) := ns (by decide)"
        )
        if s["op"] == "dbl":
            step = f"dbl_step (l := {s['l']}) ns{i} (by decide) (by decide) (by decide) (by decide)"
            rhs = f"chain {prev} {prev} ({step}) (by decide)"
        else:
            step = f"add_step (l := {s['l']}) ns{i} (by decide) (by decide) (by decide) (by decide)"
            rhs = f"chain {prev} t0 ({step}) (by decide)"
        out.append(
            f"private theorem t{i} : Point.some ns{i} = ({s['k']} : ℕ) • "
            f"Point.some G_nonsingular_nat :=\n  {rhs}"
        )
    last = len(steps)
    out.append(
        f"""
/-- **`n • G = 0`** on secp256k1, by the addition chain above (`n` as a literal). -/
theorem cert_nsmul_eq_zero : ({N} : ℕ) • Point.some G_nonsingular_nat = 0 := by
  rw [show ({N} : ℕ) = {N - 1} + 1 from rfl, add_nsmul, one_nsmul, ← t{last}]
  exact neg_step (by decide) (by decide)

end Secp256k1Primality.Order
"""
    )
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument(
        "--check",
        action="store_true",
        help="compare against the file at --out instead of writing it",
    )
    args = ap.parse_args()
    text = generate()
    if args.check:
        if args.out.read_text() == text:
            print(f"{args.out}: matches generate() exactly")
            return 0
        print(f"{args.out}: DIFFERS from generate()", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
